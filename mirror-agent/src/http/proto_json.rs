//! Protobuf JSON conversion shared by HTTP responses and JSONL journals.

use std::io;
use std::sync::LazyLock;

use mirror_agent::AgentMessage;
use prost::{Message, Name};
use prost_reflect::{DescriptorPool, DynamicMessage};

static SCHEMA: LazyLock<DescriptorPool> = LazyLock::new(|| {
    DescriptorPool::decode(mirror_agent::FILE_DESCRIPTOR_SET)
        .expect("embedded descriptors are generated by protoc in the protocol build")
});

/// Encode committed conversation records identically for file and HTTP exports.
pub fn native_jsonl(entries: &[AgentMessage]) -> io::Result<Vec<u8>> {
    let mut buffer = Vec::new();
    for entry in entries {
        serde_json::to_writer(&mut buffer, &dynamic_message(entry)?)?;
        buffer.push(b'\n');
    }
    Ok(buffer)
}

/// Reflect a native message for canonical or explicitly configured JSON encoding.
pub fn dynamic_message<M: Message + Name>(message: &M) -> io::Result<DynamicMessage> {
    let descriptor = SCHEMA
        .get_message_by_name(&M::full_name())
        .ok_or_else(|| io::Error::other("missing protobuf JSON descriptor"))?;
    let mut dynamic = DynamicMessage::new(descriptor);
    dynamic.transcode_from(message).map_err(io::Error::other)?;
    Ok(dynamic)
}
